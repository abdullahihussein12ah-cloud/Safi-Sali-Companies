import mongoose from 'mongoose';

const employeeDetailsSchema = new mongoose.Schema(
  {
    firstName: { type: String, default: '' },
    middleName: { type: String, default: '' },
    lastName: { type: String, default: '' },
    serialNumber: { type: String, default: '' },
    gender: { type: String, enum: ['', 'female', 'male'], default: '' },
    nationality: { type: String, default: '' },
    residenceType: { type: String, enum: ['', 'local', 'foreigner'], default: '' },
    nationalId: { type: String, default: '' },
    passportNumber: { type: String, default: '' },
    payrollInvited: { type: Boolean, default: false },
    jobTitle: { type: String, default: '' },
    department: { type: String, default: '' },
    employmentType: { type: String, default: '' },
    employmentStartDate: { type: String, default: '' },
    employmentStatus: { type: String, enum: ['active', 'on_leave', 'terminated'], default: 'active' },
    bankName: { type: String, default: '' },
    bankAccountNumber: { type: String, default: '' },
    medicalNotes: { type: String, default: '' },
    emergencyContactName: { type: String, default: '' },
    emergencyContactRelationship: { type: String, default: '' },
    emergencyContactPhone: { type: String, default: '' },
    emergencyContactAddress: { type: String, default: '' },
    evcPlusPhone: { type: String, default: '' },
    zaadPhone: { type: String, default: '' },
    sahalPhone: { type: String, default: '' },
    photo: { type: String, default: '' },
  },
  { _id: false }
);

const userSchema = new mongoose.Schema(
  {
    name: { type: String, required: true, trim: true },
    email: { type: String, required: true, unique: true, lowercase: true, trim: true },
    phone: { type: String, default: '' },
    tenantId: { type: String, default: 'business', index: true },
    createdBy: { type: String, default: '' },
    createdByName: { type: String, default: '' },
    dateOfBirth: { type: String, default: '' },
    address: { type: String, default: '' },
    jobTitle: { type: String, default: '' },
    monthlySalary: { type: Number, min: 0, default: 0 },
    employeeDetails: { type: employeeDetailsSchema, default: () => ({}) },
    role: {
      type: String,
      enum: [
        'admin',
        'manager',
        'cashier',
        'accountant',
        'business_owner',
        'business_admin',
        'branch_manager',
        'inventory_manager',
        'hr_manager',
        'employee',
        'super_admin',
      ],
      required: true,
    },
    isEmailVerified: { type: Boolean, default: true },
    emailVerificationCodeHash: { type: String, select: false },
    emailVerificationCodeExpiresAt: { type: Date, select: false },
    emailVerificationCodeAttempts: { type: Number, select: false, default: 0 },
    emailVerificationCodeSentAt: { type: Date, select: false },
    passwordHash: { type: String, required: true, select: false },
    passwordResetTokenHash: { type: String, select: false },
    passwordResetExpiresAt: { type: Date, select: false },
    passwordResetCodeHash: { type: String, select: false },
    passwordResetCodeExpiresAt: { type: Date, select: false },
    passwordResetCodeAttempts: { type: Number, select: false, default: 0 },
    passwordResetCodeSentAt: { type: Date, select: false },
    tokenVersion: { type: Number, default: 0 },
    active: { type: Boolean, default: true },
    deletedAt: { type: Date, default: null, index: true },
    deletedBy: { type: String, default: '' },
    deletedByName: { type: String, default: '' },
    wasActiveBeforeDeletion: { type: Boolean, default: true },
  },
  { timestamps: true }
);

export const UserModel = mongoose.model('User', userSchema);
